function build(rows: Row[], category: string, subject: FactItem['subject'], prefix: string): FactItem[] {
  return rows.map(([term, clue, tier]) => ({
    term,
    clue: `${prefix}${clue}`,
    category,
    subject,
    tier,
  }))
}

